#!/usr/bin/env node

import { randomUUID } from 'node:crypto';
import { linkSync, lstatSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import {
  exitIfChildProcess,
  exitIfWrongFlavor,
  failOpen,
  logHookLine,
  readStdin,
  writeHookOutput,
} from './lib/hook-utils.mjs';

const HOOK_NAME = 'sync-codex-agents';
const GENERATED_HEADER = '# Generated by the Coral plugin.\n';

function tomlString(value) {
  return JSON.stringify(value).replaceAll('\x7f', '\\u007f');
}

function readDefinition(sourcePath) {
  const markdown = readFileSync(sourcePath, 'utf8');
  const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(markdown);
  if (!frontmatter) throw new Error(`Missing agent frontmatter in ${sourcePath}`);

  const name = /^name:[ \t]*([a-z0-9]+(?:-[a-z0-9]+)*)[ \t]*$/m.exec(frontmatter[1])?.[1];
  // Coral's agent descriptions are single-line YAML scalars.
  const raw = /^description:[ \t]*(.+)$/m.exec(frontmatter[1])?.[1].trim() ?? '';
  let description = raw;
  if (raw.startsWith('"')) description = JSON.parse(raw);
  if (raw.startsWith("'") && raw.endsWith("'")) description = raw.slice(1, -1).replaceAll("''", "'");
  const instructions = markdown.slice(frontmatter[0].length).trim();
  if (!name || !description.trim() || !instructions) throw new Error(`Incomplete agent definition in ${sourcePath}`);

  return (
    GENERATED_HEADER +
    `name = ${tomlString(`coral:${name}`)}\n` +
    `description = ${tomlString(description)}\n` +
    `developer_instructions = ${tomlString(instructions)}\n`
  );
}

function syncDefinition(destination, content) {
  const currentFile = lstatSync(destination, { throwIfNoEntry: false });
  if (currentFile) {
    const current = currentFile.isFile() ? readFileSync(destination, 'utf8') : '';
    if (current === content) return false;
    if (!current.startsWith(GENERATED_HEADER)) {
      logHookLine(HOOK_NAME, 'Preserving a user-owned agent file', { path: destination });
      return false;
    }
  }

  // Publish complete files so other Codex sessions cannot read a partial TOML.
  const temporary = `${destination}.${randomUUID()}.tmp`;
  try {
    writeFileSync(temporary, content, { flag: 'wx', mode: 0o600 });
    if (currentFile) {
      renameSync(temporary, destination);
    } else {
      // An installation racing with a file created at this path must leave it intact.
      linkSync(temporary, destination);
    }
    return true;
  } catch (error) {
    if (!currentFile && error?.code === 'EEXIST') return false;
    throw error;
  } finally {
    rmSync(temporary, { force: true });
  }
}

exitIfChildProcess();
exitIfWrongFlavor();

await failOpen(async () => {
  const input = JSON.parse(await readStdin());
  const pluginRoot = process.env.PLUGIN_ROOT;
  if (input?.hook_event_name !== 'SessionStart' || !pluginRoot) return;

  const source = join(pluginRoot, 'agents');
  const destination = join(process.env.CODEX_HOME || join(homedir(), '.codex'), 'agents');
  const entries = readdirSync(source, { withFileTypes: true });
  mkdirSync(destination, { recursive: true, mode: 0o700 });

  let changed = false;
  for (const entry of entries) {
    const name = /^([a-z0-9]+(?:-[a-z0-9]+)*)\.md$/.exec(entry.name)?.[1];
    if (!entry.isFile() || !name) continue;
    await failOpen(() => {
      const content = readDefinition(join(source, entry.name));
      if (syncDefinition(join(destination, `coral-${name}.toml`), content)) changed = true;
    }, HOOK_NAME);
  }

  if (changed) {
    writeHookOutput({
      systemMessage: 'Coral synced its Codex agents. Open a new thread to load the updated agent list.',
    });
  }
}, HOOK_NAME);
